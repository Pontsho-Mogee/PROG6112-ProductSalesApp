    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        
        String customerName = txtCustomerName.getText();
        String productName = cmbProductName.getSelectedItem().toString();

try {
    double price = Double.parseDouble(txtProductPrice.getText());

    double vat = price * 0.15;
    double commission = price * 0.05;
    double totalSale = price + vat + commission;

    txtVAT.setText(String.format("%.2f", vat));
    txtCommission.setText(String.format("%.2f", commission));
    txtTotalSale.setText(String.format("%.2f", totalSale));

    try (java.io.PrintWriter writer = new java.io.PrintWriter(
            new java.io.FileWriter("data.txt", true))) {

        writer.println("Customer Name: " + customerName);
        writer.println("Product Name: " + productName);
        writer.println("Product Price: R" + price);
        writer.println("VAT: R" + vat);
        writer.println("Commission: R" + commission);
        writer.println("Total Sale: R" + totalSale);
        writer.println("-------------------------");
    }

    javax.swing.JOptionPane.showMessageDialog(this,
            "Sale processed and saved successfully!");

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter a valid product price.");
} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error saving the sale: " + e.getMessage());
}
    }//GEN-LAST:event_btnProcessActionPerformed

